let built: ReturnType<typeof build> | undefined

/**
 * The files, built on first use and not when this module loads. That is what keeps them out of the production Worker:
 * worker.ts imports dev.ts, and a table built at load (it decodes base64) is work a bundler must keep, with every byte of
 * it; a function nothing in a build calls is dropped.
 */
export const devFiles = (): ReturnType<typeof build> => {
  built ??= build()
  return built
}
