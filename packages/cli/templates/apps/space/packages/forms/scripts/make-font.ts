// Turns the font files in src/pdf/fonts/ into the two modules the app imports:
//
//   src/pdf/font-data.ts   the font bytes as base64 (the Worker has no file system, and this loads the same in bun, vite and workerd),
//                          with the font's version, licence and the SHA-256 of each file, which test/font.test.ts pins
//   src/pdf/coverage.ts    which code points the font can draw, as ranges: small enough for the browser to import, so a question's
//                          text is refused where it is typed, by the very rule the PDF is drawn with
//
//   bun scripts/make-font.ts          (after src/pdf/fonts/README.md's subsetting step, only when the font files change)
import { PDF } from '@libpdf/core'
import { readFileSync, writeFileSync } from 'node:fs'
import { sha256Hex } from '../src/bytes'

const dir = new URL('../src/pdf/fonts/', import.meta.url)
const files = { regular: 'NotoSans-Regular.subset.ttf', bold: 'NotoSans-Bold.subset.ttf' } as const
const bytes = Object.fromEntries(Object.entries(files).map(([k, f]) => [k, new Uint8Array(readFileSync(new URL(f, dir)))])) as Record<keyof typeof files, Uint8Array>

/** The font's own version string (name ID 5) from its name table, read directly so the pinned version is the file's, not a claim. */
function versionOf(ttf: Uint8Array): string {
  const v = new DataView(ttf.buffer, ttf.byteOffset, ttf.byteLength)
  const tables = v.getUint16(4)
  for (let i = 0; i < tables; i++) {
    const at = 12 + i * 16
    if (String.fromCharCode(...ttf.slice(at, at + 4)) !== 'name') continue
    const table = v.getUint32(at + 8)
    const count = v.getUint16(table + 2)
    const strings = table + v.getUint16(table + 4)
    for (let n = 0; n < count; n++) {
      const rec = table + 6 + n * 12
      if (v.getUint16(rec + 6) !== 5 || v.getUint16(rec) !== 3) continue
      const len = v.getUint16(rec + 8)
      const off = strings + v.getUint16(rec + 10)
      let s = ''
      for (let k = 0; k < len; k += 2) s += String.fromCharCode(v.getUint16(off + k))
      return s.split(';')[0]!.replace(/^Version\s+/, '').trim()
    }
  }
  throw new Error('no version in the font')
}

const version = versionOf(bytes.regular)
if (versionOf(bytes.bold) !== version) throw new Error('the regular and bold files are different versions')

// Coverage: every code point the font has a glyph for, as [first, last] ranges.
const probe = PDF.create().embedFont(bytes.regular)
const ranges: [number, number][] = []
for (let cp = 0x20; cp <= 0x2200; cp++) {
  if (cp >= 0x7f && cp < 0xa0) continue
  if (!probe.canEncode(String.fromCodePoint(cp))) continue
  const last = ranges[ranges.length - 1]
  if (last && last[1] === cp - 1) last[1] = cp
  else ranges.push([cp, cp])
}

const b64 = (b: Uint8Array) => Buffer.from(b).toString('base64')
const hexed = (n: number) => `0x${n.toString(16)}`
writeFileSync(
  new URL('../src/pdf/font-data.ts', import.meta.url),
  `// GENERATED by scripts/make-font.ts from src/pdf/fonts/*.subset.ttf. Do not edit.
// Noto Sans, subset to Basic Latin, Latin-1, Latin Extended A and B, Vietnamese and the other Latin Extended Additional letters, combining
// marks, Greek, Cyrillic, general punctuation and currency signs. Licensed under the SIL Open Font License 1.1 (src/pdf/fonts/OFL.txt).
export const FONT = {
  family: 'Noto Sans',
  version: ${JSON.stringify(version)},
  license: 'SIL Open Font License 1.1',
  licenseFile: 'src/pdf/fonts/OFL.txt',
  source: 'https://github.com/notofonts/latin-greek-cyrillic',
  sha256: { regular: ${JSON.stringify(await sha256Hex(bytes.regular))}, bold: ${JSON.stringify(await sha256Hex(bytes.bold))} },
} as const

export const REGULAR_BASE64 = '${b64(bytes.regular)}'
export const BOLD_BASE64 = '${b64(bytes.bold)}'
`,
)
writeFileSync(
  new URL('../src/pdf/coverage.ts', import.meta.url),
  `// GENERATED by scripts/make-font.ts from the font's own character map. Do not edit.
// The code points the document's font (src/pdf/font-data.ts) can draw, as inclusive ranges.
export const COVERED: readonly (readonly [number, number])[] = [${ranges.map(([a, b]) => `[${hexed(a)}, ${hexed(b)}]`).join(', ')}]
`,
)
console.log(`${version}: ${ranges.length} ranges, regular ${bytes.regular.length} bytes, bold ${bytes.bold.length} bytes`)
